export function resolveVehicleColors(
  vehicle: VehicleConfig,
  swatchId?: string
): { primary: string; secondary: string; isCustom: boolean } {
  if (!swatchId || swatchId === 'default') {
    return { primary: vehicle.primaryColor, secondary: vehicle.secondaryColor, isCustom: false };
  }
  const found = VEHICLE_PAINT_SWATCHES.find((s) => s.id === swatchId);
  if (!found || !found.primary) {
    return { primary: vehicle.primaryColor, secondary: vehicle.secondaryColor, isCustom: false };
  }
  return { primary: found.primary, secondary: found.secondary, isCustom: true };
}

export function resolveDriverOutfitColors(
  driver: DriverConfig,
  swatchId?: string
): { primary: string; secondary: string; accent: string; isCustom: boolean } {
  if (!swatchId || swatchId === 'default') {
    return {
      primary: driver.defaultOutfitPrimary,
      secondary: driver.defaultOutfitSecondary,
      accent: driver.accentColor,
      isCustom: false,
    };
  }
  const found = DRIVER_OUTFIT_SWATCHES.find((s) => s.id === swatchId);
  if (!found || !found.primary) {
    return {
      primary: driver.defaultOutfitPrimary,
      secondary: driver.defaultOutfitSecondary,
      accent: driver.accentColor,
      isCustom: false,
    };
  }
  return {
    primary: found.primary,
    secondary: found.secondary,
    accent: found.accent,
    isCustom: true,
  };
}

